import re
from pathlib import Path
from typing import Final

from PIL import Image, ImageDraw, ImageFont
from rich.progress import track

from utils import settings
from utils.console import print_step, print_substep

__all__ = ["get_screenshots_of_reddit_posts"]


def _setting(path: list[str], default):
    """Read a config value, but keep local testing easy if config was not loaded."""
    value = settings.config
    try:
        for key in path:
            value = value[key]
        return value
    except (AttributeError, KeyError, TypeError):
        return default


def _alpha_from_opacity(opacity: float) -> int:
    return max(0, min(255, round(float(opacity) * 255)))


def _load_font(size: int, bold: bool = False):
    """Use the bundled fonts when possible and Pillow's default font otherwise."""
    font_names = ["Roboto-Bold.ttf", "Rubik-Bold.ttf"] if bold else ["Roboto-Regular.ttf"]
    for font_name in font_names:
        font_path = Path("fonts") / font_name
        if font_path.exists():
            return ImageFont.truetype(str(font_path), size=size)
    return ImageFont.load_default()


def _wrap_text(text: str, font: ImageFont.ImageFont, max_width: int) -> list[str]:
    """Wrap text by measuring pixels instead of guessing only by character count."""
    lines = []
    for paragraph in text.splitlines() or [""]:
        words = paragraph.split()
        current_line = ""
        for word in words:
            next_line = f"{current_line} {word}".strip()
            if font.getlength(next_line) <= max_width:
                current_line = next_line
            else:
                if current_line:
                    lines.append(current_line)
                current_line = word
        if current_line:
            lines.append(current_line)
        if not words:
            lines.append("")
    return lines


def _text_height(lines: list[str], font: ImageFont.ImageFont, line_gap: int) -> int:
    """Calculate the height needed for a block of wrapped text."""
    if not lines:
        return 0
    box = font.getbbox("Ag")
    line_height = box[3] - box[1]
    return (line_height * len(lines)) + (line_gap * (len(lines) - 1))


def _draw_card(
    path: Path,
    title: str,
    body: str,
    meta: str,
    *,
    background: tuple[int, int, int, int],
    text_color: tuple[int, int, int],
    muted_color: tuple[int, int, int],
    border_color: tuple[int, int, int],
):
    """Create a simple Reddit-style card PNG for the video overlay."""
    width = 900
    padding = 44
    title_font = _load_font(38, bold=True)
    body_font = _load_font(31)
    meta_font = _load_font(23)
    max_text_width = width - (padding * 2)

    title_lines = _wrap_text(title, title_font, max_text_width)
    body_lines = _wrap_text(body, body_font, max_text_width)
    title_gap = 16
    body_gap = 12
    section_gap = 24

    height = (
        padding
        + _text_height([meta], meta_font, 0)
        + section_gap
        + _text_height(title_lines, title_font, title_gap)
        + section_gap
        + _text_height(body_lines, body_font, body_gap)
        + padding
    )
    height = max(height, 260)

    image = Image.new("RGBA", (width, height), background)
    draw = ImageDraw.Draw(image)

    # A light outline helps transparent and dark cards remain readable on video.
    draw.rounded_rectangle(
        (1, 1, width - 2, height - 2),
        radius=28,
        outline=border_color,
        width=2,
    )

    y = padding
    draw.text((padding, y), meta, font=meta_font, fill=muted_color)
    y += _text_height([meta], meta_font, 0) + section_gap

    for line in title_lines:
        draw.text((padding, y), line, font=title_font, fill=text_color)
        y += _text_height([line], title_font, 0) + title_gap

    y += section_gap - title_gap
    for line in body_lines:
        draw.text((padding, y), line, font=body_font, fill=text_color)
        y += _text_height([line], body_font, 0) + body_gap

    image.save(path)


def get_screenshots_of_reddit_posts(reddit_object: dict, screenshot_num: int):
    """Generate local PNG cards for the existing video pipeline.

    Args:
        reddit_object (Dict): Reddit object received from reddit/subreddit.py
        screenshot_num (int): Last comment index generated by the TTS step
    """
    # settings values
    storymode: Final[bool] = _setting(["settings", "storymode"], False)

    print_step("Generating local PNG cards...")
    reddit_id = re.sub(r"[^\w\s-]", "", reddit_object["thread_id"])
    png_dir = Path(f"assets/temp/{reddit_id}/png")
    png_dir.mkdir(parents=True, exist_ok=True)

    # Match the old theme settings closely enough for the downstream overlay.
    theme = _setting(["settings", "theme"], "dark")
    story_bg_alpha = _alpha_from_opacity(
        _setting(["settings", "story_text_background_opacity"], 1.0)
    )
    if theme == "dark":
        bgcolor = (33, 33, 36, story_bg_alpha)
        txtcolor = (240, 240, 240)
        mutedcolor = (165, 170, 176)
        bordercolor = (70, 70, 76)
        transparent = False
    elif theme == "transparent":
        if storymode:
            bgcolor = (0, 0, 0, 0)
            txtcolor = (255, 255, 255)
            mutedcolor = (215, 215, 215)
            bordercolor = (255, 255, 255)
            transparent = True
        else:
            bgcolor = (33, 33, 36, 255)
            txtcolor = (240, 240, 240)
            mutedcolor = (165, 170, 176)
            bordercolor = (70, 70, 76)
            transparent = False
    else:
        bgcolor = (255, 255, 255, story_bg_alpha)
        txtcolor = (0, 0, 0)
        mutedcolor = (95, 99, 104)
        bordercolor = (220, 220, 220)
        transparent = False

    if storymode and _setting(["settings", "storymodemethod"], 0) == 1:
        from utils.imagenarator import imagemaker

        print_substep("Generating images...")
        return imagemaker(
            theme=bgcolor,
            reddit_obj=reddit_object,
            txtclr=txtcolor,
            transparent=transparent,
        )

    _draw_card(
        png_dir / "title.png",
        reddit_object["thread_title"],
        "",
        "r/local",
        background=bgcolor,
        text_color=txtcolor,
        muted_color=mutedcolor,
        border_color=bordercolor,
    )

    if storymode:
        _draw_card(
            png_dir / "story_content.png",
            reddit_object["thread_title"],
            reddit_object.get("thread_post", ""),
            "Story",
            background=bgcolor,
            text_color=txtcolor,
            muted_color=mutedcolor,
            border_color=bordercolor,
        )
    else:
        # save_text_to_mp3 returns the last comment index, and final_video reads
        # comment_0.png through comment_{screenshot_num}.png.
        comments_to_render = reddit_object["comments"][: screenshot_num + 1]
        for idx, comment in enumerate(track(comments_to_render, "Generating cards...")):
            _draw_card(
                png_dir / f"comment_{idx}.png",
                f"Comment {idx + 1}",
                comment["comment_body"],
                "u/local_story",
                background=bgcolor,
                text_color=txtcolor,
                muted_color=mutedcolor,
                border_color=bordercolor,
            )

    print_substep("Local PNG cards generated successfully.", style="bold green")
